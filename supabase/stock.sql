-- 1) 테이블 ---------------------------------------------------------------
-- 보유 생산 설비 (이름은 세 언어 공통)
create table if not exists public.facility_equipment (
  id    bigint generated by default as identity primary key,
  name  text not null,
  qty   integer not null default 0 check (qty >= 0),
  sort  integer not null default 0
);

-- STOCK 구성 (분류별 수량, 합계가 "총 N Set")
create table if not exists public.stock_groups (
  id        bigint generated by default as identity primary key,
  label_ko  text not null,
  label_en  text,
  label_zh  text,
  qty       integer not null default 0 check (qty >= 0),
  sort      integer not null default 0
);

-- STOCK 상세 표
create table if not exists public.stock_items (
  id        bigint generated by default as identity primary key,
  model_ko  text not null,
  model_en  text,
  model_zh  text,
  maker_ko  text not null default '',
  maker_en  text,
  maker_zh  text,
  size      text not null default '',
  qty       integer not null default 0 check (qty >= 0),
  sort      integer not null default 0
);

-- 2) 권한 (누구나 읽기, 매니저만 쓰기) -------------------------------------
do $$
declare t text;
begin
  foreach t in array array['facility_equipment', 'stock_groups', 'stock_items'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "%s read" on public.%I', t, t);
    execute format('drop policy if exists "%s write" on public.%I', t, t);
    execute format('create policy "%s read" on public.%I for select using (true)', t, t);
    execute format('create policy "%s write" on public.%I for all to authenticated using (public.is_gallery_admin()) with check (public.is_gallery_admin())', t, t);
  end loop;
end $$;

